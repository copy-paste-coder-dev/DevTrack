import { test, expect } from '../support/test'

test('release happy path persists settings, full-day logging, gap fill, duplicate, status, calendar, delete and re-login', async ({
  page,
}) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error') errors.push(message.text())
  })
  await page.addInitScript(() => {
    if (!localStorage.getItem('devtrack-e2e-session'))
      localStorage.setItem('devtrack-e2e-session', 'null')
    if (!localStorage.getItem('devtrack-e2e-activities'))
      localStorage.setItem('devtrack-e2e-activities', JSON.stringify({ 'test-developer': [] }))
  })
  await page.goto('/app/settings')
  await expect(page).toHaveURL(/\/login/)
  await page.getByRole('button', { name: 'Continue with Google' }).click()
  await expect(page.getByLabel('Default day start time')).toHaveValue('09:00')
  await expect(page.getByLabel('Default day end time')).toHaveValue('18:00')
  await page.getByLabel('Time display format').selectOption('12h')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Settings saved.')).toBeVisible()
  await page.goto('/app?date=2026-10-12')
  async function add(name: string, type: string, start: string, end: string) {
    await page.getByRole('button', { name: 'Add activity', exact: true }).click()
    await expect(page.getByLabel(/^Start time/)).toHaveValue(start)
    await page.getByLabel('Task / activity name').fill(name)
    await page.getByLabel('Activity type').selectOption(type)
    await page.getByLabel(/^End time/).fill(end)
    await page.getByRole('button', { name: 'Save activity' }).click()
    await expect(page.getByRole('dialog')).not.toBeVisible()
  }
  await add('Release Jira', 'jira_task', '09:00', '10:00')
  await add('Release Scrum', 'scrum_call', '10:00', '10:30')
  await add('Release Development', 'development', '10:30', '12:00')
  await page.getByRole('button', { name: 'Add activity', exact: true }).click()
  await page.getByLabel('Task / activity name').fill('Release Meeting')
  await page.getByLabel('Activity type').selectOption('meeting')
  await page.getByLabel(/^Start time/).fill('13:00')
  await page.getByLabel(/^End time/).fill('13:30')
  await page.getByRole('button', { name: 'Save activity' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.locator('.timeline-gap button').click()
  await expect(page.getByLabel(/^Start time/)).toHaveValue('12:00')
  await expect(page.getByLabel(/^End time/)).toHaveValue('13:00')
  await page.getByLabel('Task / activity name').fill('Release Lunch')
  await page.getByLabel('Activity type').selectOption('break')
  await page.getByRole('button', { name: 'Save activity' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.timeline-gap')).toHaveCount(0)
  await page.getByRole('button', { name: 'More actions for Release Jira', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click()
  await expect(page.getByLabel(/^Start time/)).toHaveValue('13:30')
  await expect(page.getByLabel(/^End time/)).toHaveValue('14:30')
  await page.getByLabel('Task / activity name').fill('Release Jira duplicate')
  await page.getByRole('button', { name: 'Save activity' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const duplicate = page.locator('.timeline-item').filter({ hasText: 'Release Jira duplicate' })
  await duplicate.getByRole('button', { name: 'Edit Jira Task', exact: true }).click()
  await page.getByLabel('Task status').selectOption('completed')
  await page.getByRole('button', { name: 'Update activity' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(duplicate).toContainText('Completed')
  await expect(page.locator('.stat-card').first()).toContainText('5h 30m')
  await page.goto('/app/calendar?date=2026-10-12')
  await expect(page.locator('.timeline-item')).toHaveCount(6)
  await page.getByRole('button', { name: 'More actions for Release Meeting', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.timeline-item')).toHaveCount(5)
  await expect(page.locator('.timeline-gap')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.timeline-item')).toHaveCount(5)
  await page.getByRole('button', { name: 'Logout', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  await page.getByRole('button', { name: 'Continue with Google' }).click()
  await expect(page).toHaveURL(/\/app(?:[/?]|$)/)
  await page.goto('/app?date=2026-10-12')
  await expect(page.locator('.timeline-item')).toHaveCount(5)
  await expect(page.locator('.stat-card').first()).toContainText('5h')
  await expect(page.locator('.activity-time').first()).toContainText('9:00 AM')
  await page.goto('/app/settings')
  await expect(page.getByLabel('Time display format')).toHaveValue('12h')
  expect(errors).toEqual([])
})
